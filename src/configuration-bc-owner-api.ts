// ECC INSERT REPORT 拒绝超过255字符的源码行；只在字符常量之外断行。
function eccSourceLines(line: string): string[] {
  const result: string[] = []
  while (line.length > 255) {
    let quoted = false
    let split = -1
    for (let i = 0; i < 255; i++) {
      if (line[i] === "'") {
        if (quoted && line[i + 1] === "'") i++
        else quoted = !quoted
      } else if (!quoted && line[i] === " ") split = i
    }
    if (split <= 0) throw new Error("BC_OWNER_SOURCE_TOKEN_TOO_LONG")
    result.push(line.slice(0, split))
    line = line.slice(split + 1)
  }
  result.push(line)
  return result
}
