const makeApi = (kind: "APPLY" | "RECOVER" | "RECONCILE") => {
  const recon = kind === "RECONCILE"
  return {
    functionName: `Z_ORVANTA_CFG_BC_${kind}`,
    functionGroup: "ZORVANTA_BC_CFG",
    remoteEnabled: true,
    importParameters: [
      ...configurationBcOwnerImports.map((n) => parameter(`IV_${n}`)),
      ...(recon ? [parameter("IV_COMMAND")] : [])
    ],
    exportParameters: configurationBcOwnerExports.map((n) => parameter(`EV_${n}`)),
    tableParameters: [],
    source: [
      "DATA: ls_args TYPE ty_orv_bc_args, ls_result TYPE ty_orv_bc_result.",
      ...configurationBcOwnerImports.map(
        (n) => `ls_args-${n.toLowerCase()} = iv_${n.toLowerCase()}.`
      ),
      recon
        ? "ls_args-command = iv_command."
        : `ls_args-command = '${kind === "APPLY" ? "A" : "R"}'.`,
      `PERFORM orv_bc_owner USING '${recon ? "X" : " "}' ls_args CHANGING ls_result.`,
      ...configurationBcOwnerExports.map(
        (n) => `ev_${n.toLowerCase()} = ls_result-${n.toLowerCase()}.`
      )
    ]
  }
}
