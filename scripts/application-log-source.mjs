// Fill the four SOURCE|HASH slots with the body digest. The digest is taken over the body with the
// slots still in place, so it is self-referential in the same way as the other helpers' bodies.
export const injectCapabilityHash = (lines) => {
  const digest = createHash("sha256").update(lines.join("\n")).digest("hex")
  const groups = HASH_SLOTS.map((slot, index) => [slot, digest.slice(index * 16, (index + 1) * 16)])
  const filled = lines.map((line) => {
    let out = line
    for (const [slot, group] of groups) out = out.split(slot).join(group)
    return out
  })
  if (filled.join("\n").includes("ORVANTAHASHSLOT"))
    throw new Error("a hash slot was left unfilled")
  return filled
}

